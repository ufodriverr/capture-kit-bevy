"""Writes THIRD-PARTY-NOTICES.md and licenses/<crate>-<version>/ from the resolved dependency graph.

Usage (repo root): python -I tools/licenses.py [target triple, default x86_64-pc-windows-msvc]
Run it again whenever Cargo.lock changes. Needs cargo on PATH and the crates downloaded (cargo fetch).
"""
import collections
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = sys.argv[1] if len(sys.argv) > 1 else "x86_64-pc-windows-msvc"
NOTICE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "authors", "unlicense")

meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET], cwd=ROOT, capture_output=True, text=True, check=True).stdout)
members = set(meta["workspace_members"])
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
pkgs = {p["id"]: p for p in meta["packages"]}

# Everything the workspace members need at run time (normal deps; build deps are compile-time only but
# their code can end up in the binary through macros, so they are listed too; dev deps are not).
seen, stack = set(), list(members)
while stack:
    cur = stack.pop()
    for d in nodes[cur]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]) and d["pkg"] not in seen:
            seen.add(d["pkg"])
            stack.append(d["pkg"])
deps = sorted((pkgs[i] for i in seen if i not in members), key=lambda p: (p["name"], p["version"]))

out = ROOT / "licenses"
if out.exists():
    for child in out.iterdir():
        if child.is_dir() and child.name != "_standard-texts":
            shutil.rmtree(child)
out.mkdir(exist_ok=True)
no_file, counts = [], collections.Counter()
for p in deps:
    lic = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "UNKNOWN")
    counts[lic] += 1
    src = Path(p["manifest_path"]).parent
    files = [f for f in src.iterdir() if f.is_file() and f.name.lower().startswith(NOTICE_PREFIXES)]
    if not files:
        no_file.append(f"`{p['name']}-{p['version']}` ({lic})")
        continue
    dst = out / f"{p['name']}-{p['version']}"
    dst.mkdir()
    for f in files:
        shutil.copy2(f, dst / f.name)

lines = [
    "# Third-party notices",
    "",
    "Capture Kit (Bevy) is licensed under MIT OR Apache-2.0 (see `LICENSE-MIT` and `LICENSE-APACHE`). It is built",
    f"from the Rust crates below (the {TARGET} dependency graph of `Cargo.lock`), each under its own licence as",
    "declared in its package metadata (reproduced as declared, including legacy slash notation). The crates' own",
    "licence and notice files are kept in `licenses/<crate>-<version>/` and ship with releases.",
    "",
    "Generated by `tools/licenses.py`; run it again after changing dependencies.",
    "",
]
if no_file:
    lines += [
        "These crates publish no licence file of their own; their declared licence applies, with the standard text",
        "of that licence (MIT and Apache-2.0 in `licenses/_standard-texts/`): " + ", ".join(no_file) + ".",
        "",
    ]
lines += ["## Licence summary", "", "| Licence | Crates |", "| --- | --- |"]
lines += [f"| {k} | {v} |" for k, v in counts.most_common()]
lines += ["", "## Crates", "", "| Crate | Version | Licence | Source |", "| --- | --- | --- | --- |"]
for p in deps:
    lic = p.get("license") or "see licence file"
    repo = p.get("repository") or ""
    lines.append(f"| {p['name']} | {p['version']} | {lic} | {repo} |")
(ROOT / "THIRD-PARTY-NOTICES.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(deps)} crates, {len(no_file)} without a licence file")
